export function getBusinessTranslations(locale: string) {
  return businessTranslations[businessLocale(locale)]
}

export function businessStatusLabel(status: string, locale: string): string {
  const text = getBusinessTranslations(locale)
  const labels: Record<string, string> = {
    DRAFT: text.statusDraft,
    PENDING: text.statusPending,
    APPROVED: text.statusApproved,
    CHANGES_REQUESTED: text.statusChangesRequested,
    SUSPENDED: text.statusSuspended,
  }
  return labels[status] || status.replaceAll('_', ' ')
}

export function serviceAreaLabel(area: string, locale: string): string {
  const text = getBusinessTranslations(locale)
  const labels: Record<string, string> = { LOCAL: text.local, NATIONWIDE: text.nationwide, ONLINE: text.online, INTERNATIONAL: text.international }
  return labels[area] || area
}

export function locationVisibilityLabel(visibility: string, locale: string): string {
  const text = getBusinessTranslations(locale)
  const labels: Record<string, string> = { CITY_ONLY: text.showCityOnly, EXACT: text.showFullAddress, ONLINE_ONLY: text.onlineOnly }
  return labels[visibility] || visibility
}

